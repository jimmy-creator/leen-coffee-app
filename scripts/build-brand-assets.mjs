/**
 * Build the app icons from the client's logo.
 *
 * Sources are the transparent masters in `brand/`, lifted out of
 * `brand/leen-coffee-logo.pdf`. Re-run this after replacing either master;
 * nothing else has to change.
 *
 *   node scripts/build-brand-assets.mjs
 *
 * Why the mark and not the full lockup on the icon: at 48 px on a home screen
 * the "LEEN COFFEE" wordmark is an illegible smudge. The lotus alone is
 * distinctive at any size, which is what an icon has to be. The lockup is used
 * for the splash, where there is room to read it.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import sharp from 'sharp';

/** Sampled from the logo PDF. */
const BRAND = '#1C3819';

const SIZE = 1024;

/** Compose a mark onto a square canvas at a given proportion of its width. */
async function icon({ source, background, scale, out }) {
  const target = Math.round(SIZE * scale);
  const mark = await sharp(source)
    .resize({ width: target, height: target, fit: 'inside' })
    .toBuffer();

  const canvas = background
    ? sharp({ create: { width: SIZE, height: SIZE, channels: 4, background } })
    : sharp({
        create: { width: SIZE, height: SIZE, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } },
      });

  await canvas.composite([{ input: mark, gravity: 'center' }]).png().toFile(out);
  console.log('wrote', out);
}

/**
 * Each app takes the same mark; only the field changes, so the three are
 * distinguishable on one home screen while staying obviously one family.
 * The customer app carries the brand green — it is the one the public sees.
 */
const APPS = [
  { dir: 'customer-mobile', field: BRAND },
  { dir: 'merchant-mobile', field: '#122611' },
  { dir: 'delivery-mobile', field: '#2C5127' },
];

for (const app of APPS) {
  const out = `apps/${app.dir}/assets`;
  mkdirSync(out, { recursive: true });

  // Store icon: mark on the app's field, generous margin so it survives the
  // rounded-rect crop iOS applies.
  await icon({ source: 'brand/mark-white.png', background: app.field, scale: 0.66, out: `${out}/icon.png` });

  // Android adaptive foreground: transparent, and smaller still — OEM masks cut
  // aggressively, and anything outside the centre 62% can be clipped.
  await icon({ source: 'brand/mark-white.png', background: null, scale: 0.5, out: `${out}/icon-adaptive.png` });

  // Splash: the full lockup, on the splash background set in app.json.
  await icon({ source: 'brand/lockup-white.png', background: null, scale: 0.62, out: `${out}/leen-logo.png` });

  writeFileSync(
    `${out}/README.md`,
    '# App icons\n\n' +
      'Generated by `scripts/build-brand-assets.mjs` from the masters in `brand/`,\n' +
      "which were lifted from the client's `brand/leen-coffee-logo.pdf`.\n\n" +
      'Do not hand-edit these. Replace the masters and re-run the script.\n',
  );
}
