/**
 * Generate placeholder app icons for the three Leen apps.
 *
 * These are NOT the brand. They exist because app.json references icon files
 * and a build fails without them — a coffee-bean mark in the Leen palette reads
 * as "placeholder" far better than a pink Expo default. Replace the outputs when
 * the real logo arrives; nothing else has to change.
 *
 * Pure vector, no text: the render happens through librsvg, whose font coverage
 * on a build machine is not something to bet an Arabic wordmark on.
 *
 * Usage: node scripts/make-brand-assets.mjs
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import sharp from 'sharp';

const ESPRESSO = '#3B2418';
const CREAM = '#F8F4EE';
const CARAMEL = '#C58B55';
const FOREST = '#1F4D3A';

/** A coffee bean: rotated ellipse with the centre crease cut through it. */
const bean = (fill, crease, scale = 1) => `
  <g transform="translate(512 512) rotate(-20) scale(${scale})">
    <ellipse cx="0" cy="0" rx="196" ry="286" fill="${fill}"/>
    <path d="M 0,-262 C -78,-150 78,-44 0,66 C -66,166 -14,224 0,262"
          fill="none" stroke="${crease}" stroke-width="34" stroke-linecap="round"/>
  </g>`;

const svg = (body, bg) => `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  ${bg ? `<rect width="1024" height="1024" fill="${bg}"/>` : ''}
  ${body}
</svg>`;

/**
 * Each app gets its own accent so the three are distinguishable on a home
 * screen and in the EAS dashboard: cream for the customer, caramel for the
 * roastery, forest for the rider.
 */
const APPS = [
  { dir: 'customer-mobile', field: ESPRESSO, mark: CREAM, adaptiveBg: CREAM, adaptiveMark: ESPRESSO },
  { dir: 'merchant-mobile', field: ESPRESSO, mark: CARAMEL, adaptiveBg: ESPRESSO, adaptiveMark: CARAMEL },
  { dir: 'delivery-mobile', field: FOREST, mark: CREAM, adaptiveBg: FOREST, adaptiveMark: CREAM },
];

const png = (markup, out) =>
  sharp(Buffer.from(markup)).png().toFile(out).then(() => console.log('wrote', out));

for (const app of APPS) {
  const dir = `apps/${app.dir}/assets`;
  mkdirSync(dir, { recursive: true });

  // Store icon: full bleed.
  await png(svg(bean(app.mark, app.field), app.field), `${dir}/icon.png`);

  // Android adaptive foreground: transparent, and scaled to ~62% so the mark
  // survives the aggressive circular and squircle masks OEMs apply.
  await png(svg(bean(app.adaptiveMark, app.adaptiveBg, 0.62), null), `${dir}/icon-adaptive.png`);

  // Splash mark: sits on the profile's own background colour.
  await png(svg(bean(app.adaptiveMark, app.adaptiveBg, 0.78), null), `${dir}/leen-logo.png`);

  writeFileSync(
    `${dir}/README.md`,
    '# Placeholder brand assets\n\n' +
      'Generated by `scripts/make-brand-assets.mjs`. These are not the Leen brand —\n' +
      'they exist so the app config resolves and builds succeed. Drop the real\n' +
      '1024×1024 `icon.png`, `icon-adaptive.png` (transparent, mark inside the\n' +
      'centre 62%) and `leen-logo.png` over them when the client supplies artwork.\n',
  );
}
